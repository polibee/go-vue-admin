package generator

import (
	"fmt"
	"go/format"
	"path/filepath"
	"strings"
)

type Artifact struct {
	Path    string
	Content []byte
}

func Render(spec Spec, migrationTimestamp string) ([]Artifact, error) {
	base := filepath.ToSlash(filepath.Join("app", "generated", "resources", spec.Name))
	packageName := strings.ReplaceAll(spec.Name, "-", "_")

	files := []struct {
		name string
		body string
	}{
		{"manifest.go", manifestSource(spec, packageName)},
		{"model.go", modelSource(spec, packageName)},
		{"request.go", plainSource(packageName, "Request")},
		{"repository.go", plainSource(packageName, "Repository")},
		{"service.go", plainSource(packageName, "Service")},
		{"controller.go", plainSource(packageName, "Controller")},
		{"routes.go", plainSource(packageName, "Routes")},
		{"permissions.go", permissionsSource(spec, packageName)},
		{"manifest_test.go", manifestTestSource(spec, packageName)},
	}

	artifacts := make([]Artifact, 0, len(files)+1)
	for _, file := range files {
		content, err := format.Source([]byte(file.body))
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", file.name, err)
		}
		artifacts = append(artifacts, Artifact{Path: filepath.ToSlash(filepath.Join(base, file.name)), Content: content})
	}

	migration := migrationSource(spec, packageName)
	migrationContent, err := format.Source([]byte(migration))
	if err != nil {
		return nil, fmt.Errorf("format migration: %w", err)
	}
	artifacts = append(artifacts, Artifact{
		Path:    filepath.ToSlash(filepath.Join("database", "migrations", migrationTimestamp+"_create_"+spec.Name+"_table.go")),
		Content: migrationContent,
	})
	return artifacts, nil
}

func manifestSource(spec Spec, packageName string) string {
	var fields strings.Builder
	var columns strings.Builder
	for _, field := range spec.Fields {
		label := humanize(field.Name)
		fmt.Fprintf(&fields, "\t\t{Name: %q, Label: %q, Type: %q},\n", field.Name, label, field.Type)
		fmt.Fprintf(&columns, "\t\t{Name: %q, Label: %q, Sortable: true},\n", field.Name, label)
	}
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
package %s

import "goravel/app/resource"

func Manifest() resource.Manifest {
	return resource.Manifest{
		Name: %q, Label: %q, Route: %q, Permissions: []string{%q},
		Fields: []resource.Field{
%s		},
		Columns: []resource.Column{
%s		},
	}
}
`, packageName, spec.Name, spec.Label, spec.Route, spec.Permission, fields.String(), columns.String())
}

func modelSource(spec Spec, packageName string) string {
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
package %s

import "github.com/goravel/framework/database/orm"

type %s struct {
	orm.Model
%s}
`, packageName, spec.GoName, modelFields(spec))
}

func modelFields(spec Spec) string {
	var result strings.Builder
	for _, field := range spec.Fields {
		goType := "string"
		switch field.Type {
		case "integer":
			goType = "int"
		case "boolean":
			goType = "bool"
		}
		fmt.Fprintf(&result, "\t%s %s `json:%q`\n", field.GoName, goType, field.Name)
	}
	return result.String()
}

func plainSource(packageName, typeName string) string {
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
package %s

// %s is an integration boundary for the generated resource.
type %s struct{}
`, packageName, typeName, typeName)
}

func permissionsSource(spec Spec, packageName string) string {
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
package %s

const ViewPermission = %q
`, packageName, spec.Permission)
}

func manifestTestSource(spec Spec, packageName string) string {
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
package %s

import "testing"

func TestManifestHasResourceIdentity(t *testing.T) {
	manifest := Manifest()
	if manifest.Name != %q || manifest.Route != %q {
		t.Fatalf("unexpected manifest: %%+v", manifest)
	}
}
`, packageName, spec.Name, spec.Route)
}

func migrationSource(spec Spec, packageName string) string {
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
package migrations

import (
	"github.com/goravel/framework/contracts/database/schema"
	"github.com/goravel/framework/database/schema/grammars"
)

type Create%sTable struct{}

func (m *Create%sTable) Up() error { return nil }
func (m *Create%sTable) Down() error { return nil }

var _ schema.Grammar = (*grammars.PostgresGrammar)(nil)
`, packageName, packageName, packageName)
}
