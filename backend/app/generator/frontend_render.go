func frontendTestSource(spec Spec) string {
	return fmt.Sprintf(`import { resourceDefinition } from './resource';

// This contract check uses the existing Node type/runtime surface; the generator
// does not add a frontend test-runner dependency.
if (resourceDefinition.name !== %q) throw new Error('generated resource name mismatch');
if (resourceDefinition.route !== %q) throw new Error('generated resource route mismatch');
if (JSON.stringify(resourceDefinition.actions) !== JSON.stringify(%s)) throw new Error('generated resource actions mismatch');
`, spec.Name, spec.FrontendRoute, frontendActionList(spec))
}

func frontendFields(spec Spec) string {
	parts := make([]string, 0, len(spec.Fields))
	for _, field := range spec.Fields {
		options := ""
		if len(field.Options) > 0 {
			values := make([]string, 0, len(field.Options))
			for _, option := range field.Options {
				values = append(values, fmt.Sprintf("{ value: %q, label: %q }", option.Value, option.Label))
			}
			options = ", options: [" + strings.Join(values, ", ") + "]"
		}
		parts = append(parts, fmt.Sprintf("{ name: %q, label: %q, type: %q, required: %t, visible: %t, readable: %t, writable: %t, sensitive: %t%s }", field.Name, humanize(field.Name), field.Type, field.Required, fieldBool(field.Visible), fieldBool(field.Readable), fieldBool(field.Writable), field.Sensitive, options))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func quoteList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func frontendActionList(spec Spec) string {
	items := make([]string, 0, len(spec.ActionSpecs))
	for _, action := range spec.ActionSpecs {
		items = append(items, fmt.Sprintf("{ name: %q, label: %q, kind: %q, permission: %q, batch: %t, payload: %q }", action.Name, action.Label, action.Kind, action.Permission, action.Batch, action.Payload))
	}
	return "[" + strings.Join(items, ", ") + "]"
}

func frontendRelations(spec Spec) string {
	items := make([]string, 0, len(spec.Relations))
	for _, relation := range spec.Relations {
		items = append(items, fmt.Sprintf("{ name: %q, kind: %q, resource: %q, field: %q, foreign_field: %q, label_field: %q, selectable: %t, multiple: false }", relation.Name, relation.Kind, relation.Resource, relation.Field, relation.ForeignField, relation.LabelField, relation.Selectable))
	}
	return "[" + strings.Join(items, ", ") + "]"
}

func frontendFormGroups(spec Spec) string {
	items := make([]string, 0, len(spec.FormGroups))
	for _, group := range spec.FormGroups {
		items = append(items, fmt.Sprintf("{ name: %q, label: %q, columns: %d, fields: %s }", group.Name, group.Label, group.Columns, quoteList(group.Fields)))
	}
	return "[" + strings.Join(items, ", ") + "]"
}

func frontendDetails(spec Spec) string {
	items := make([]string, 0, len(spec.Details))
	for _, section := range spec.Details {
		items = append(items, fmt.Sprintf("{ name: %q, label: %q, fields: %s }", section.Name, section.Label, quoteList(section.Fields)))
	}
	return "[" + strings.Join(items, ", ") + "]"
}
