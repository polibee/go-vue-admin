package generator

import (
	"fmt"
	"path/filepath"
	"strings"
)

func RenderFrontend(spec Spec) ([]Artifact, error) {
	base := filepath.ToSlash(filepath.Join("admin", "src", "modules", spec.Name))
	pageBase := filepath.ToSlash(filepath.Join(base, "pages"))
	files := []struct {
		path string
		body string
	}{
		{filepath.Join(base, "resource.ts"), frontendResourceSource(spec)},
		{filepath.Join(base, "api.ts"), frontendAPISource(spec)},
		{filepath.Join(pageBase, spec.GoName+"ListPage.vue"), frontendListPageSource(spec)},
		{filepath.Join(pageBase, spec.GoName+"FormPage.vue"), frontendFormPageSource(spec)},
		{filepath.Join(pageBase, spec.GoName+"DetailPage.vue"), frontendDetailPageSource(spec)},
		{filepath.Join(base, spec.Name+".test.ts"), frontendTestSource(spec)},
	}
	artifacts := make([]Artifact, 0, len(files))
	for _, file := range files {
		artifacts = append(artifacts, Artifact{Path: filepath.ToSlash(file.path), Content: []byte(file.body)})
	}
	return artifacts, nil
}

func frontendResourceSource(spec Spec) string {
	scopeMetadata := ""
	if spec.DataScope == "own" {
		scopeMetadata = fmt.Sprintf("  dataScope: %q,\n  ownerField: %q,\n", spec.DataScope, spec.OwnerField)
	}
	return fmt.Sprintf(`// Code generated by admin:make-resource. DO NOT EDIT.
export const resourceDefinition = {
  name: %q,
  label: %q,
  route: %q,
  permission: %q,
  icon: %q,
  navigation: { group: "business", order: 100 },
%s
  actions: %s,
  relations: %s,
  form_groups: %s,
  details: %s,
  fields: %s,
} as const;
`, spec.Name, spec.Label, spec.FrontendRoute, spec.Permission, spec.Icon, scopeMetadata, frontendActionList(spec), frontendRelations(spec), frontendFormGroups(spec), frontendDetails(spec), frontendFields(spec))
}

