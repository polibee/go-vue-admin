import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'

const [, , documentPath, outputDir] = process.argv
if (!documentPath || !outputDir) {
  throw new Error('usage: node scripts/generate-ts-client.mjs <openapi.json> <output-dir>')
}

const document = JSON.parse(await readFile(documentPath, 'utf8'))
const resourcePaths = Object.keys(document.paths)
  .filter((value) => value.startsWith('/api/resources/') && !value.endsWith('/{id}') && !value.endsWith('/bulk-delete'))
  .map((value) => value.split('/')[3])

const pascal = (value) => value.split(/[-_]/).map((part) => part[0].toUpperCase() + part.slice(1)).join('')
const singular = (value) => value === 'demo' ? 'Demo' : pascal(value.replace(/s$/, ''))
const modelName = (resource) => `${singular(resource)}Resource`
const pluralMethod = (resource) => resource === 'demo' ? 'DemoResources' : pascal(resource)
const operationMethod = (resource, action) => {
  const single = singular(resource)
  if (resource === 'demo') return action === 'list' || action === 'bulkDelete' ? `${action === 'bulkDelete' ? 'bulkDelete' : 'list'}${pluralMethod(resource)}` : `${action}${single}Resource`
  if (action === 'list' || action === 'bulkDelete') return `${action === 'bulkDelete' ? 'bulkDelete' : 'list'}${pluralMethod(resource)}`
  return `${action}${single}`
}

const schemaTypes = {
  string: 'string', integer: 'number', number: 'number', boolean: 'boolean', object: 'Record<string, unknown>',
}
const typeOf = (schema) => {
  if (!schema) return 'unknown'
  if (schema.$ref) return schema.$ref.split('/').at(-1)
  if (schema.type === 'array') return `${typeOf(schema.items)}[]`
  return schemaTypes[schema.type] ?? 'unknown'
}

const schemas = document.components?.schemas ?? {}
const resourceInterfaces = resourcePaths.map((resource) => {
  const schema = schemas[modelName(resource)] ?? { properties: {} }
  const properties = Object.entries(schema.properties ?? {}).map(([name, value]) => `  ${name}: ${typeOf(value)}`).join('\n')
  return `export interface ${modelName(resource)} {\n${properties}\n}`
}).join('\n\n')

const models = `/* eslint-disable */
// This file is generated by scripts/openapi-generate.sh. Do not edit by hand.

export interface ResourceListQuery {
  page?: number
  perPage?: number
  search?: string
  filters?: Record<string, string>
  sort?: { field: string; direction: 'asc' | 'desc' }
}

export interface ResourcePagination {
  page: number
  per_page: number
  total: number
  total_pages: number
}

export interface ResourceEnvelope<T> {
  data: T
  meta?: { request_id?: string; pagination?: ResourcePagination }
}

${resourceInterfaces}
`

const methods = resourcePaths.map((resource) => {
  const method = singular(resource)
  const model = modelName(resource)
  return `  ${operationMethod(resource, 'list')}(query?: ResourceListQuery): Promise<ResourceEnvelope<${model}[]>>
  ${operationMethod(resource, 'get')}(id: string): Promise<ResourceEnvelope<${model}>>
  ${operationMethod(resource, 'create')}(input: ${model}): Promise<ResourceEnvelope<${model}>>
  ${operationMethod(resource, 'update')}(id: string, input: Partial<${model}>): Promise<ResourceEnvelope<${model}>>
  ${operationMethod(resource, 'delete')}(id: string): Promise<ResourceEnvelope<{ deleted: boolean }>>
  ${operationMethod(resource, 'bulkDelete')}(input: { ids: string[] }): Promise<ResourceEnvelope<{ deleted: boolean }>>`
}).join('\n')

const implementations = resourcePaths.map((resource) => {
  const model = modelName(resource)
  const base = `/api/resources/${resource}`
  return `    ${operationMethod(resource, 'list')}: (query) => client.request<ResourceEnvelope<${model}[]>>(withQuery('${base}', query)),
    ${operationMethod(resource, 'get')}: (id) => client.request<ResourceEnvelope<${model}>>(itemPath('${base}', id)),
    ${operationMethod(resource, 'create')}: (input) => client.request<ResourceEnvelope<${model}>>('${base}', jsonOptions('POST', input)),
    ${operationMethod(resource, 'update')}: (id, input) => client.request<ResourceEnvelope<${model}>>(itemPath('${base}', id), jsonOptions('PUT', input)),
    ${operationMethod(resource, 'delete')}: (id) => client.request<ResourceEnvelope<{ deleted: boolean }>>(itemPath('${base}', id), { method: 'DELETE' }),
    ${operationMethod(resource, 'bulkDelete')}: (input) => client.request<ResourceEnvelope<{ deleted: boolean }>>('${base}/bulk-delete', jsonOptions('POST', input)),`
}).join('\n')

const client = `/* eslint-disable */
// This file is generated by scripts/openapi-generate.sh. Do not edit by hand.

import type { ApiClient } from '@/core/api/client'

import type { ${resourcePaths.flatMap((resource) => [modelName(resource)]).join(', ')}, ResourceEnvelope, ResourceListQuery } from './models'

export interface GeneratedApiClient {
${methods}
}

function withQuery(path: string, query?: ResourceListQuery): string {
  if (!query) return path
  const params = new URLSearchParams()
  if (query.page !== undefined) params.set('page', String(query.page))
  if (query.perPage !== undefined) params.set('per_page', String(query.perPage))
  if (query.search?.trim()) params.set('search', query.search.trim())
  if (query.sort) {
    params.set('sort', query.sort.field)
    params.set('sort_dir', query.sort.direction)
  }
  for (const [field, value] of Object.entries(query.filters ?? {}).sort(([left], [right]) => left.localeCompare(right))) {
    params.set('filter[' + field + ']', value)
  }
  const serialized = params.toString()
  return serialized ? path + '?' + serialized : path
}

function itemPath(path: string, id: string): string {
  return path + '/' + encodeURIComponent(id)
}

function jsonOptions(method: string, body: unknown): RequestInit {
  return { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }
}

export function createGeneratedApiClient(client: ApiClient): GeneratedApiClient {
  return {
${implementations}
  }
}
`

await rm(outputDir, { recursive: true, force: true })
await mkdir(outputDir, { recursive: true })
await writeFile(path.join(outputDir, 'models.ts'), models)
await writeFile(path.join(outputDir, 'client.ts'), client)
await writeFile(path.join(outputDir, 'index.ts'), `// This file is generated by scripts/openapi-generate.sh. Do not edit by hand.\nexport * from './models'\nexport * from './client'\n`)
